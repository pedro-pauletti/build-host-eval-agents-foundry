<#
.SYNOPSIS
  Provision the Zava Foundry demo core infrastructure into rg-zava-demo (East US 2).

.DESCRIPTION
  Deploys infra/main.bicep at subscription scope. Captures the deployment outputs into
  a repo-root .env file (and optionally the azd environment) for the notebooks/scripts.

  Prereqs: az CLI logged in (az login). You need Owner/Contributor on the subscription.

.EXAMPLE
  ./scripts/provision.ps1
  ./scripts/provision.ps1 -Location eastus2 -EnvName zava-demo
#>
[CmdletBinding()]
param(
  [string]$EnvName = 'zava-demo',
  [string]$Location = 'eastus2',
  [string]$ResourceGroup = 'rg-zava-demo',
  [string]$SubscriptionId = ''
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot

if ($SubscriptionId) { az account set --subscription $SubscriptionId | Out-Null }
$sub = az account show --query id -o tsv
$principalId = az ad signed-in-user show --query id -o tsv
Write-Host "Subscription : $sub"
Write-Host "Deploying user objectId: $principalId"
Write-Host "Target RG    : $ResourceGroup ($Location)"

$deploymentName = "zava-$([DateTime]::UtcNow.ToString('yyyyMMddHHmmss'))"

Write-Host "`nStarting deployment '$deploymentName' ... (this can take 5-10 minutes)" -ForegroundColor Cyan
$depOut = az deployment sub create `
  --name $deploymentName `
  --location $Location `
  --template-file (Join-Path $repoRoot 'infra/main.bicep') `
  --parameters environmentName=$EnvName location=$Location resourceGroupName=$ResourceGroup principalId=$principalId `
  --output json 2>&1

if ($LASTEXITCODE -ne 0) {
  Write-Host ($depOut | Out-String) -ForegroundColor Red
  throw "Deployment failed. See errors above."
}

Write-Host "`nDeployment complete. Reading outputs ..." -ForegroundColor Green
$outputs = az deployment sub show --name $deploymentName --query properties.outputs -o json | ConvertFrom-Json

$envPath = Join-Path $repoRoot '.env'
# Merge with any existing .env so custom keys (e.g. ZAVA_MCP_URL from deploy_backend) survive re-runs.
$existing = [ordered]@{}
if (Test-Path $envPath) {
  foreach ($line in Get-Content $envPath) {
    if ($line -match '^\s*#' -or ($line -notmatch '=')) { continue }
    $i = $line.IndexOf('='); $existing[$line.Substring(0, $i)] = $line.Substring($i + 1)
  }
}
$existing['AZURE_ENV_NAME'] = $EnvName
$existing['AZURE_SUBSCRIPTION_ID'] = $sub
foreach ($p in $outputs.PSObject.Properties) {
  # ARM mangles output-name casing; normalize keys to UPPER_SNAKE_CASE.
  $existing[$p.Name.ToUpper()] = $p.Value.value
}
$consts = [ordered]@{
  'FOUNDRY_MODEL_DEPLOYMENT_NAME' = 'gpt-4.1'
  'MODEL_ROUTER_DEPLOYMENT_NAME'  = 'model-router'
  'EMBEDDING_DEPLOYMENT_NAME'     = 'text-embedding-3-large'
  'REALTIME_DEPLOYMENT_NAME'      = 'gpt-realtime-mini'
  'AZURE_SEARCH_INDEX_NAME'       = 'zava-docs'
}
# Fabric is provisioned outside this Bicep deployment, so carry the workspace id over only when
# the caller supplies it.
if ($env:FABRIC_WORKSPACE_ID) { $consts['FABRIC_WORKSPACE_ID'] = $env:FABRIC_WORKSPACE_ID }
foreach ($k in $consts.Keys) { if (-not $existing.Contains($k)) { $existing[$k] = $consts[$k] } }
$lines = @('# Generated by scripts/provision.ps1 - do not commit')
foreach ($k in $existing.Keys) { $lines += "$k=$($existing[$k])" }
$lines | Set-Content -Path $envPath -Encoding utf8
Write-Host "Wrote $($lines.Count) values to $envPath" -ForegroundColor Green

Write-Host "`nKey endpoints:" -ForegroundColor Cyan
$outputs.PSObject.Properties | Where-Object { $_.Name -match 'ENDPOINT|NAME' } |
  ForEach-Object { "  {0} = {1}" -f $_.Name, $_.Value.value }

Write-Host "`nNext: index docs (scripts/index_docs.py), deploy backends (scripts/deploy_backend.ps1)." -ForegroundColor Yellow
